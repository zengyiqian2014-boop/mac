<h2>Introduction</h2>

<img src="https://upload.wikimedia.org/wikipedia/commons/c/c3/Mohenjo-daro_Sindh.jpeg">

<p>
Throughout history, humans have depended heavily on natural environments for survival.
The earliest civilisations developed near rivers because rivers provided water,
fertile soil, transportation routes, and opportunities for trade. Over time,
these settlements became highly organised societies with governments, engineering systems,
religious structures, and agricultural networks. Ancient civilisations did not simply survive;
they transformed their environments through planning, innovation, and cooperation.

The Indus Valley Civilization, Ancient Egypt, and Ancient Greece are among the most influential
societies in world history. Each civilisation developed unique methods to manage water,
organise cities, support agriculture, and maintain stability. Their systems demonstrate
human creativity and adaptability in response to geographical challenges.

The Indus Valley Civilization is especially recognised for advanced urban planning.
Cities such as Mohenjo-daro were built using organised grid systems and drainage networks
that were highly sophisticated for their time. The civilisation used standardised baked bricks,
private wells, and covered drains to improve hygiene and infrastructure. These features suggest
strong leadership, planning, and understanding of environmental management.

Ancient Egypt depended heavily on the Nile River. The predictable flooding cycle deposited
fertile silt onto farmland, allowing Egyptians to grow crops efficiently.
To maximise agricultural productivity, Egyptians developed irrigation systems including canals,
basins, and water-lifting devices such as the shadoof. These systems supported population growth
and economic development for thousands of years.

Ancient Greece contributed significantly to engineering and scientific development.
Greek societies experimented with water-powered technology, including waterwheels used
to grind grain and improve efficiency. Greek thinkers also studied mathematics,
architecture, and mechanics, influencing later engineering systems in Europe and beyond.

Modern Singapore faces very different environmental conditions compared to ancient civilisations.
Unlike river valley societies, Singapore has limited land and natural freshwater resources.
However, Singapore also demonstrates how careful planning and technological innovation can support
a large population in a challenging environment. Through systems such as reservoirs,
desalination plants, and NEWater recycling, Singapore ensures long-term water security.

One important similarity between ancient civilisations and modern Singapore is the emphasis on
sustainability. Ancient societies needed stable food supplies, reliable water access,
and organised infrastructure to survive. Singapore also relies on long-term planning,
efficient land use, and environmental management. Although technologies have changed,
the underlying principles remain similar.

This project examines how geography shaped ancient civilisations and how their ideas continue
to influence modern urban development. By studying these societies, we can better understand
how humans adapt to environmental challenges and develop sustainable systems for future generations.
</p>

