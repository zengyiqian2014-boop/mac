        <h3>Structural Thermal Lag</h3>
        <p>The Harappans pioneered the use of kiln-fired bricks with a standard 1:2:4 ratio. This mass-produced, standardized material provided incredible thermal inertia. During the day, the thick, heat-absorbent walls of the residential structures absorbed incident solar radiation. This delayed the heat transfer into the interior space (thermal lag). By the time the heat would have penetrated the interior, the sun had set, and the cooler night air began to cool the walls. This natural cycle maintained stable indoor temperatures without energy consumption.</p>
        <h3>Sanitation and Public Welfare</h3>
        <p>While often overlooked, the Indus sanitation system was the most advanced in the ancient world. Their sophisticated drainage system featured covered sewers, manholes, and soak pits to prevent contamination. This focus on public health enabled high-density living without the common plagues that devastated other contemporary civilisations.</p>
